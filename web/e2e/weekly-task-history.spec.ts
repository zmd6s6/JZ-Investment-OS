import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const fixture=JSON.parse(readFileSync(new URL('../../.runtime/mvp409-browser-fixture.json',import.meta.url),'utf8'));
const headers={Authorization:'Bearer synthetic-weekly-history-only'};
test.beforeEach(async({context})=>{await context.addInitScript(()=>sessionStorage.setItem('investment_os_write_token','synthetic-weekly-history-only'));});
for(const protocol of ['1.0','2.0']) {
 test(`real ${protocol} weekly audit reaches old failed and skipped tasks and original Worker artifact`,async({page,request})=>{
  test.setTimeout(90000);
  const record=fixture.protocols[protocol], namespace=protocol==='1.0'?'weekly':'complete-weekly';
  const base=`/api/v1/opportunities/${namespace}/tasks`, key=protocol==='1.0'?'weekly_task_id':'complete_weekly_task_id';
  expect((await request.get(base)).status()).toBe(401);
  await expect.poll(async()=>{
   const data=await(await request.get(base,{headers})).json();
   return data.items?.some((item:{result_status:string|null;schedule_id:string})=>item.schedule_id===record.cli_schedule_id&&['COMPLETE','DEGRADED','EMPTY'].includes(item.result_status??''));
  },{timeout:30000}).toBe(true);
  const first=await(await request.get(base,{headers})).json();
  expect(first.items).toHaveLength(50);
  expect(first.items.some((item:{task_run_id:string})=>item.task_run_id===record.oldest_failed_id)).toBe(false);
  const real=first.items.find((item:{result_status:string|null;schedule_id:string})=>item.schedule_id===record.cli_schedule_id&&['COMPLETE','DEGRADED','EMPTY'].includes(item.result_status??''));
  const realDetail=await(await request.get(`${base}/${real.task_run_id}`,{headers})).json();
  expect(realDetail.funnel_run_id).not.toBeNull();
  await page.goto(`/opportunities?${key}=${record.oldest_failed_id}`);
  const panel=page.getByRole('region',{name:protocol==='1.0'?'本地周任务审计':'完整来源周任务审计'});
  let selected=panel.getByRole('region',{name:'原周任务审计详情'});
  await expect(selected).toContainText(record.old_revision_name);
  await expect(selected).toContainText('任务失败');
  await expect(selected).toContainText('本任务没有可核验的筛选产物');
  await expect(panel.getByText(/已加载50条/)).toBeVisible();
  await page.route(`**/opportunities/${namespace}/tasks?cursor=*`,route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:{message:'合成分页读取失败'}})}));
  await panel.getByRole('button',{name:'加载更早周任务'}).click();
  await expect(panel.getByRole('alert')).toBeVisible();
  await expect(panel.getByText(/已加载50条/)).toBeVisible();
  await page.unroute(`**/opportunities/${namespace}/tasks?cursor=*`);
  await panel.getByRole('button',{name:'加载更早周任务'}).click();
  await expect(panel.getByText(new RegExp(`已加载${record.expected_count}条`))).toBeVisible();
  await page.reload();
  selected=panel.getByRole('region',{name:'原周任务审计详情'});
  await expect(selected).toContainText(record.oldest_failed_id);
  await panel.getByLabel('精确周任务ID').fill(record.skipped_id);
  await panel.getByRole('button',{name:'打开精确周任务'}).click();
  await expect(selected).toContainText('SKIPPED_CLOSED');
  await expect(selected.getByRole('link')).toHaveCount(0);
  await panel.getByRole('button',{name:`查看原周任务 ${real.task_run_id}`}).click();
  await expect(selected.getByRole('link',{name:'查看原周筛选产物'})).toBeVisible();
  const originalLink=selected.getByRole('link',{name:'查看原周筛选产物'});
  await expect(originalLink).toHaveAttribute('href',`/opportunities?${protocol==='1.0'?'run_id':'complete_run_id'}=${realDetail.funnel_run_id}`);
  await page.route(`**/opportunities/${namespace}/tasks/${real.task_run_id}`,route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":{"message":"合成详情失败"}}'}));
  await panel.getByRole('button',{name:'刷新所选周任务'}).click();
  await expect(selected).toHaveCount(0);
  await expect(panel.getByRole('link',{name:'查看原周筛选产物'})).toHaveCount(0);
  await page.unroute(`**/opportunities/${namespace}/tasks/${real.task_run_id}`);
  await panel.getByRole('button',{name:'刷新所选周任务'}).click();
  await expect(selected).toContainText(real.task_run_id);
  // Hold one real GET while the owner selects another record; fetch cancellation may be ignored.
  let release!:()=>void;const gate=new Promise<void>(resolve=>{release=resolve;});
  await page.route(`**/opportunities/${namespace}/tasks/${real.task_run_id}`,async route=>{await gate;await route.continue().catch(()=>{});});
  await panel.getByRole('button',{name:'刷新所选周任务'}).click();
  await panel.getByRole('button',{name:`查看原周任务 ${first.items[1].task_run_id}`}).click();
  await expect(selected).toContainText(first.items[1].task_run_id);
  release();
  await expect(selected).toContainText(first.items[1].task_run_id);
  await page.unroute(`**/opportunities/${namespace}/tasks/${real.task_run_id}`);
  await panel.getByRole('button',{name:`查看原周任务 ${real.task_run_id}`}).click();
  await expect(selected).toContainText(realDetail.funnel_hash);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>({body:document.body.scrollWidth,viewport:innerWidth}))).toEqual({body:390,viewport:390});
  await selected.screenshot({path:`.runtime/mvp409-${namespace}-detail-390.png`});
  await selected.getByRole('link',{name:'查看原周筛选产物'}).click();
  await expect(page).toHaveURL(new RegExp(`${protocol==='1.0'?'run_id':'complete_run_id'}=${realDetail.funnel_run_id}`));
  await expect(page.getByText(realDetail.funnel_run_id,{exact:false}).first()).toBeVisible();
  const replay=await(await request.get(`${base}/${real.task_run_id}`,{headers})).json();
  expect(replay.funnel_hash).toBe(realDetail.funnel_hash);
  expect((await request.get(`${base}/malformed`,{headers})).status()).toBe(422);
 });
}
