import { expect, test } from "@playwright/test";

test("日历导入默认暂停，明确启用后由真实Worker保存状态报告并可刷新暂停", async ({page,request},testInfo)=>{
  test.skip(process.env.E2E_BASE_URL!=="http://127.0.0.1:18110", "仅允许MVP401独占合成栈");
  const token=process.env.INVESTMENT_OS_API_WRITE_TOKEN;
  expect(token).toBeTruthy();
  await page.addInitScript(value=>sessionStorage.setItem("investment_os_write_token",value!),token);
  const writes:string[]=[];
  page.on("request",req=>{if(req.method()==="POST")writes.push(new URL(req.url()).pathname);});
  await page.goto("/settings");
  await page.getByRole("link",{name:"配置市场日历与查看运行记录"}).click();
  await expect(page.getByRole("heading",{name:"市场日历与运行状态",exact:true})).toBeVisible();
  await page.getByLabel("日历来源名称").fill("MVP401 合成验收日历（非真实来源）");
  await page.getByLabel("来源版本",{exact:true}).fill("synthetic-20261027");
  await page.getByLabel("日历CSV内容").fill("business_date,close_at\n2026-10-23,15:00\n2026-10-23,15:00");
  await page.getByLabel("我已核对来源与时段，确认有权导入这些日历数据。").check();
  await page.getByRole("button",{name:"预览日历（不保存）"}).click();
  await expect(page.getByRole("status")).toContainText("重复");
  expect((await(await request.get("/api/v1/calendar")).json()).configurations).toHaveLength(0);
  await page.getByLabel("日历CSV内容").fill("business_date,close_at\n2026-10-23,15:00\n2030-01-02,15:00");
  await expect(page.getByLabel("我已核对来源与时段，确认有权导入这些日历数据。")).not.toBeChecked();
  await page.getByLabel("我已核对来源与时段，确认有权导入这些日历数据。").check();
  await page.getByRole("button",{name:"预览日历（不保存）"}).click();
  await expect(page.getByText("业务日期 2026-10-23 · UTC收盘 2026-10-23T07:00:00Z")).toBeVisible();
  await page.getByLabel("我确认按此预览导入；新版本默认暂停，相同内容保持原启用状态。").check();
  await page.getByRole("button",{name:"确认导入日历"}).click();
  const config=page.getByRole("article",{name:"上海证券交易所日历配置"});
  await expect(config.getByRole("heading")).toContainText("已暂停");
  const paused=await(await request.get("/api/v1/calendar")).json();
  expect(paused.recent_runs).toHaveLength(0);
  expect(paused.configurations[0].enabled).toBe(false);
  await config.getByLabel("我仅启用该市场已导入时段的状态报告；不调用付费模型、研究来源或交易。").check();
  await config.getByRole("button",{name:"启用无付费状态报告"}).click();
  await expect(page.getByRole("heading",{name:/calendar_status_SSE · 状态报告已完成/})).toBeVisible({timeout:20000});
  const complete=await(await request.get("/api/v1/calendar")).json();
  expect(complete.recent_runs).toHaveLength(1);
  const report=complete.recent_runs[0].report;
  expect(report).toMatchObject({report_kind:"CALENDAR_STATUS_ONLY",business_date:"2026-10-23",auto_trade:false,paid_calls:0});
  expect(report.calendar_hash).toBe(complete.configurations[0].content_hash);
  await page.reload();
  await expect(config.getByRole("heading")).toContainText("已启用");
  await config.getByRole("button",{name:"暂停状态报告"}).click();
  await expect(config.getByRole("heading")).toContainText("已暂停");
  await expect(page.getByRole("heading",{name:/状态报告已完成/})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:testInfo.outputPath("calendar-390.png"),fullPage:true});
  expect(writes.every(path=>path.startsWith("/api/v1/calendar"))).toBe(true);
});

test("读取失败不冒充空配置，显式重试恢复且不产生写入",async({page})=>{
  let fail=true;
  const writes:string[]=[];
  page.on("request",req=>{if(req.method()==="POST")writes.push(req.url());});
  await page.route("**/api/v1/calendar",route=>fail?route.fulfill({status:503,body:"{}"}):route.continue());
  await page.goto("/calendar");
  await expect(page.getByRole("status")).toContainText("无法读取日历服务");
  await expect(page.getByText("当前日历状态未确认，请恢复读取后核对；不能据此断言没有配置。")).toBeVisible();
  await expect(page.getByRole("button",{name:"预览日历（不保存）"})).toBeDisabled();
  fail=false;
  await page.getByRole("button",{name:"刷新日历与运行记录"}).click();
  await expect(page.getByRole("status")).toHaveCount(0);
  expect(writes).toEqual([]);
});
